/**
 * Returns vocabulary configuration for a given industry ID or code.
 * @param {string} industryIdOrCode 
 * @returns {object|null} Industry vocabulary object or null if not found.
 */
export function getIndustryVocabulary(industryIdOrCode) {
  if (!industryIdOrCode) return null;
  const key = String(industryIdOrCode).trim().toUpperCase();

  if (INDUSTRY_VOCABULARY_MAP[key]) {
    return INDUSTRY_VOCABULARY_MAP[key];
  }

  // Lookup by code
  for (const entry of Object.values(INDUSTRY_VOCABULARY_MAP)) {
    if (entry.code.toUpperCase() === key) {
      return entry;
    }
  }

  return null;
}

/**
 * Returns allowed vocabulary terms for a given industry.
 * @param {string} industryIdOrCode 
 * @returns {string[]} Allowed terms
 */
export function getAllowedVocabulary(industryIdOrCode) {
  const ind = getIndustryVocabulary(industryIdOrCode);
  return ind && Array.isArray(ind.allowedTerms) ? ind.allowedTerms : [];
}

/**
 * Returns all forbidden terms (specific + categories) for a given industry.
 * @param {string} industryIdOrCode 
 * @param {object} [options]
 * @returns {string[]} Array of forbidden terms
 */
export function getForbiddenTerms(industryIdOrCode, options = {}) {
  const ind = getIndustryVocabulary(industryIdOrCode);
  if (!ind) return [];

  const forbidden = new Set(ind.specificForbiddenTerms || []);
  if (Array.isArray(ind.forbiddenContaminantCategories)) {
    for (const catId of ind.forbiddenContaminantCategories) {
      const cat = CROSS_DOMAIN_CONTAMINANT_CATEGORIES[catId];
      if (cat && Array.isArray(cat.terms)) {
        for (const t of cat.terms) forbidden.add(t);
      }
    }
  }
  return Array.from(forbidden);
}

/**
 * Detects cross-domain vocabulary leakage in a given text for a specific industry or business type.
 * 
 * @param {string} text - The input text (question, answer, deliverable, or prompt)
 * @param {string} target - Industry ID (e.g. 'IND-04'), Code (e.g. 'HEALTH_WELLNESS_MEDICAL'), or Business Type ID (e.g. 'BT-0071')
 * @param {object} [options] - Additional options:
 *   - allowExemptions: boolean (ignore if negated e.g. "برخلاف کارواش", default true)
 *   - checkCategories: boolean (also check all terms in forbidden categories, default true)
 *   - subDomain: string ('RESTAURANT', 'CAFE', 'NON_TAX_SAAS', 'TAX_SAAS', etc.)
 *   - isNonTaxSaaS: boolean (explicit flag for SaaS without tax focus)
 * @returns {object} Leakage report with violations and relevance score
 */
export function detectCrossDomainLeakage(text, target, options = {}) {
  const allowExemptions = options.allowExemptions !== false;
  const checkCategories = options.checkCategories !== false;

  let industry = null;
  let specificBtId = null;

  if (target) {
    const key = String(target).trim().toUpperCase();
    if (key.startsWith("BT-")) {
      specificBtId = key;
      if (BUSINESS_TYPES_MAP && BUSINESS_TYPES_MAP[key]) {
        industry = getIndustryVocabulary(BUSINESS_TYPES_MAP[key].industryId);
      }
    }
    if (!industry) {
      industry = getIndustryVocabulary(key);
    }
  }

  if (!industry) {
    return {
      hasLeakage: false,
      industryId: target,
      industryCode: "UNKNOWN",
      violations: [],
      error: `Industry or business type '${target}' not found in vocabulary map`,
      allowedTermsCount: 0,
      relevanceScore: 0
    };
  }

  if (!text || typeof text !== "string") {
    return {
      hasLeakage: false,
      industryId: industry.id,
      industryCode: industry.code,
      violations: [],
      allowedTermsCount: 0,
      relevanceScore: 0
    };
  }

  const normalizedText = normalizePersianText(text);
  const violations = [];
  const seenViolations = new Set();

  // Exemption / contrast prefixes in Persian with word-boundary awareness
  const exemptionPatterns = [
    /(?:^|\s)برخلاف\s+([^\s]+(?:\s+[^\s]+){0,2})/g,
    /(?:^|\s)به\s+جای\s+([^\s]+(?:\s+[^\s]+){0,2})/g,
    /(?:^|\s)نه\s+(?:به\s+)?([^\s]+(?:\s+[^\s]+){0,2})/g,
    /(?:^|\s)به\s+جز\s+([^\s]+(?:\s+[^\s]+){0,2})/g,
    /(?:^|\s)بدون\s+نیاز\s+به\s+([^\s]+(?:\s+[^\s]+){0,2})/g
  ];

  const exemptedPhrases = [];
  if (allowExemptions) {
    for (const pat of exemptionPatterns) {
      let match;
      while ((match = pat.exec(normalizedText)) !== null) {
        if (match[1]) {
          exemptedPhrases.push(match[1].trim());
        }
      }
    }
  }

  function isExempted(normTerm) {
    if (!allowExemptions) return false;
    for (const ex of exemptedPhrases) {
      if (ex === normTerm || ex.startsWith(normTerm + " ") || ex.endsWith(" " + normTerm)) {
        return true;
      }
    }
    return false;
  }

  // Active forbidden contaminant categories (cloned to allow dynamic sub-domain specialization)
  const activeForbiddenCategories = new Set(industry.forbiddenContaminantCategories || []);

  // Context-aware sub-domain rule activations (Requirement R6):
  // 1. IND-03 (Hospitality): Traditional Iranian restaurant / dining must not be assumed to be a coffee roastery
  const isDiningRestaurant = 
    options.subDomain === "RESTAURANT" ||
    (specificBtId === "BT-0071") ||
    (industry.id === "IND-03" && (
      normalizedText.includes("رستوران") ||
      normalizedText.includes("چلوکباب") ||
      normalizedText.includes("کباب") ||
      normalizedText.includes("دیزی") ||
      normalizedText.includes("طباخی") ||
      normalizedText.includes("فست فود")
    ) && !normalizedText.includes("کافه") && !normalizedText.includes("رستری"));

  if (industry.id === "IND-03" && isDiningRestaurant) {
    activeForbiddenCategories.add("COFFEE_ROASTERY_SPECIALTY");
  }

  // 2. IND-06 (Cloud Software & SaaS): Gym/General SaaS must not default to Moadian tax compliance
  const isNonTaxSaaS =
    options.subDomain === "NON_TAX_SAAS" ||
    options.isNonTaxSaaS === true ||
    (specificBtId && specificBtId !== "BT-0166" && specificBtId !== "BT-0171") ||
    (industry.id === "IND-06" && (
      normalizedText.includes("باشگاه") ||
      normalizedText.includes("crm") ||
      normalizedText.includes("مدیریت پروژه") ||
      normalizedText.includes("نوبت دهی") ||
      normalizedText.includes("فیتنس")
    ));

  if (industry.id === "IND-06" && isNonTaxSaaS) {
    activeForbiddenCategories.add("MOADIAN_TAX_OVERKILL");
  }

  // 3. IND-04 (Health, Beauty, Wellness): Salon must not receive automotive; Clinic must not generate illegal claims
  if (industry.id === "IND-04") {
    activeForbiddenCategories.add("AUTOMOTIVE_SERVICES");
    activeForbiddenCategories.add("HEAVY_MACHINING_TOLERANCE");
    activeForbiddenCategories.add("CLINICAL_UNSUBSTANTIATED_CLAIMS");
  }

  // 4. IND-25 (Textiles): Factory must not get machining tolerance questions
  if (industry.id === "IND-25") {
    activeForbiddenCategories.add("HEAVY_MACHINING_TOLERANCE");
  }

  // 5. IND-12 (Building Materials Wholesaler) or WHOLESALE: Must not receive Creator Economy vocabulary
  if (industry.id === "IND-12" || industry.primaryArchetype === "WHOLESALE") {
    activeForbiddenCategories.add("CREATOR_INFLUENCER_ECONOMY");
  }

  // 1. Check specific forbidden terms for this industry
  if (Array.isArray(industry.specificForbiddenTerms)) {
    for (const term of industry.specificForbiddenTerms) {
      const normTerm = normalizePersianText(term);
      if (!normTerm) continue;

      if (normalizedText.includes(normTerm) && !isExempted(normTerm)) {
        if (!seenViolations.has(normTerm)) {
          seenViolations.add(normTerm);
          violations.push({
            term: term,
            category: "INDUSTRY_SPECIFIC_FORBIDDEN",
            matchedText: normTerm,
            severity: "CRITICAL",
            explanation: `اصطلاح '${term}' مربوط به حوزه دیگر بوده و نفوذ آن در صنف '${industry.titleFa}' تخلف ایزولاسیون بافتار است.`,
            suggestion: `واژه یا مفهوم مرتبط با ${industry.titleFa} را جایگزین نمایید.`
          });
        }
      }
    }
  }

  // 2. Check terms from active forbidden contaminant categories
  if (checkCategories) {
    for (const catId of activeForbiddenCategories) {
      const cat = CROSS_DOMAIN_CONTAMINANT_CATEGORIES[catId];
      if (!cat || !Array.isArray(cat.terms)) continue;

      for (const catTerm of cat.terms) {
        const normTerm = normalizePersianText(catTerm);
        if (!normTerm) continue;

        if (normalizedText.includes(normTerm) && !isExempted(normTerm)) {
          if (!seenViolations.has(normTerm)) {
            seenViolations.add(normTerm);
            violations.push({
              term: catTerm,
              category: cat.id,
              matchedText: normTerm,
              severity: cat.severity || "HIGH",
              explanation: `اصطلاح '${catTerm}' از دسته '${cat.titleFa}' به صنف '${industry.titleFa}' نشت کرده است.`,
              suggestion: `از واژگان مجاز این صنف نظیر (${industry.allowedTerms.slice(0, 3).join("، ")}) استفاده شود.`
            });
          }
        }
      }
    }
  }

  // 3. Calculate allowed vocabulary presence and relevance score
  let allowedMatches = 0;
  if (Array.isArray(industry.allowedTerms)) {
    for (const allowTerm of industry.allowedTerms) {
      const normAllow = normalizePersianText(allowTerm);
      if (normAllow && normalizedText.includes(normAllow)) {
        allowedMatches++;
      }
    }
  }

  const relevanceScore = industry.allowedTerms.length > 0
    ? Math.min(100, Math.round((allowedMatches / Math.min(5, industry.allowedTerms.length)) * 100))
    : 0;

  return {
    hasLeakage: violations.length > 0,
    industryId: industry.id,
    industryCode: industry.code,
    violations,
    allowedTermsCount: allowedMatches,
    relevanceScore
  };
}

/**
 * Checks whether a single term is allowed in a given industry (not forbidden/contaminant).
 * @param {string} term
 * @param {string} industryIdOrCode
 * @returns {boolean} true if allowed, false if forbidden/contaminant
 */
export function isTermAllowedInIndustry(term, industryIdOrCode) {
  if (!term || typeof term !== "string") return true;
  const res = detectCrossDomainLeakage(term, industryIdOrCode, { allowExemptions: false });
  return !res.hasLeakage;
}
