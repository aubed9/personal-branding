def enrich():
    with open(REGISTRY_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    sources = data.get('sources', {})
    updated_count = 0

    for sid, enrichment in SOURCE_ENRICHMENTS.items():
        if sid in sources:
            src = sources[sid]
            for key, val in enrichment.items():
                src[key] = val
            updated_count += 1
            print(f"Enriched: {sid}")
        else:
            print(f"Warning: {sid} not found in sources registry!")

    with open(REGISTRY_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"\nSuccessfully enriched {updated_count} sources in {REGISTRY_PATH}.")

if __name__ == '__main__':
    enrich()
